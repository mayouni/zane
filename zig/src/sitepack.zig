//! sitepack.zig: the build's packer of the site `zane serve` embeds (build.zig, siteModule). build.zig crawls what the pages
//! reach and runs this program, built for the machine that builds, on those files:
//!
//!   sitepack OUT_DIR  REL PATH  REL PATH ...
//!
//! It writes OUT_DIR/site.zig, the module `site` of `files` (path, data, gzip, size), and beside it the bytes each entry
//! embeds. A text file is stored as gzip (gzip.zig) when that is smaller, and only after std's inflate has given every byte
//! of it back: a stream that does not read back stops the build. A file already compressed (webp, png, jpg, gif, wasm,
//! woff, woff2, ico) is stored as it is. Being a step of its own, it runs again only when one of its files changes.

const std = @import("std");
const gzip = @import("gzip.zig");

const already = [_][]const u8{ ".webp", ".png", ".jpg", ".jpeg", ".gif", ".wasm", ".woff", ".woff2", ".ico" };

pub fn main() !void {
    var arena = std.heap.ArenaAllocator.init(std.heap.page_allocator);
    defer arena.deinit();
    const a = arena.allocator();
    const args = try std.process.argsAlloc(a);
    if (args.len < 2 or args.len % 2 != 0) {
        std.debug.print("sitepack OUT_DIR [REL PATH]...\n", .{});
        std.process.exit(2);
    }
    var out = try std.fs.cwd().makeOpenPath(args[1], .{});
    defer out.close();
    var src: std.ArrayList(u8) = .empty;
    try src.appendSlice(a,
        \\// generated by zig/src/sitepack.zig: the site zane serve answers from the binary, what its pages reach, the text
        \\// stored as gzip where that is smaller (gzip true: data is the gzip stream, size the file's own length)
        \\pub const File = struct { path: []const u8, data: []const u8, gzip: bool, size: usize };
        \\pub const files = [_]File{
        \\
    );
    var raw: usize = 0;
    var stored: usize = 0;
    var packed_count: usize = 0;
    var i: usize = 2;
    while (i + 1 < args.len) : (i += 2) {
        const rel = args[i];
        const data = try std.fs.cwd().readFileAlloc(a, args[i + 1], 256 * 1024 * 1024);
        var keep: []const u8 = data;
        var gz = false;
        var compressible = true;
        for (already) |ext| if (std.ascii.endsWithIgnoreCase(rel, ext)) {
            compressible = false;
        };
        if (compressible) {
            const c = try gzip.compress(a, data);
            const back = gzip.inflate(a, c) catch |e| {
                std.debug.print("sitepack: {s}: the gzip stream does not inflate ({s})\n", .{ rel, @errorName(e) });
                std.process.exit(1);
            };
            if (!std.mem.eql(u8, back, data)) {
                std.debug.print("sitepack: {s}: the gzip stream inflates to other bytes\n", .{rel});
                std.process.exit(1);
            }
            if (c.len < data.len) {
                keep = c;
                gz = true;
                packed_count += 1;
            }
        }
        const name = if (gz) try std.fmt.allocPrint(a, "files/{s}.gz", .{rel}) else try std.fmt.allocPrint(a, "files/{s}", .{rel});
        if (std.fs.path.dirname(name)) |d| try out.makePath(d);
        try out.writeFile(.{ .sub_path = name, .data = keep });
        try src.print(a, "    .{{ .path = \"{s}\", .data = @embedFile(\"{s}\"), .gzip = {}, .size = {d} }},\n", .{ rel, name, gz, data.len });
        raw += data.len;
        stored += keep.len;
    }
    try src.print(a, "}};\n/// the files' own bytes, the bytes embedded for them, and how many are stored as gzip\npub const raw_bytes = {d};\npub const stored_bytes = {d};\npub const gzip_files = {d};\n", .{ raw, stored, packed_count });
    try out.writeFile(.{ .sub_path = "site.zig", .data = src.items });
}
