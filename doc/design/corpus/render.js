#!/usr/bin/env node
// Renders CORPUS.md from corpus.json and prints the figures the design study cites.
// node doc/design/corpus/render.js           write CORPUS.md, print the figures
// node doc/design/corpus/render.js --check   fail when CORPUS.md differs from what corpus.json renders
'use strict';
const fs = require('fs'), path = require('path');
const here = __dirname, c = JSON.parse(fs.readFileSync(path.join(here, 'corpus.json'), 'utf8'));
const R = c.records, cell = s => String(s || '').replace(/\|/g, '/');
const month = d => (String(d).match(/20\d\d-\d\d/) || ['undated'])[0];
const day = d => (String(d).match(/20\d\d-\d\d-\d\d/) || [''])[0];
const groupOf = k => c.groups.find(g => g.causes.includes(k));

function figures() {
  const f = { total: R.length, verbatim: R.filter(r => r.verbatim).length, repeat: R.filter(r => r.repeat).length,
    relays: R.reduce((n, r) => n + r.also.length, 0), requests: c.requests.length, statements: c.statements.length,
    projects: new Set(R.map(r => r.project)).size, months: {}, causes: {}, groups: {}, byProject: {},
    lastDay: R.filter(r => day(r.date) === '2026-11-09').length };
  for (const r of R) {
    f.months[month(r.date)] = (f.months[month(r.date)] || 0) + 1;
    f.byProject[r.project] = (f.byProject[r.project] || 0) + 1;
  }
  for (const k of c.order) {
    const g = R.filter(r => r.cause === k), dates = g.map(r => month(r.date)).filter(m => m !== 'undated').sort();
    f.causes[k] = { n: g.length, projects: new Set(g.map(r => r.project)).size, repeat: g.filter(r => r.repeat).length,
      first: dates[0], last: dates[dates.length - 1] };
  }
  for (const g of c.groups) f.groups[g.key] = g.causes.reduce((n, k) => n + f.causes[k].n, 0);
  return f;
}

function render(f) {
  const L = [];
  L.push('# The corpus: every UI correction the Principal made, classified by root cause', '');
  L.push('*Generated by `node doc/design/corpus/render.js` from `corpus.json`; edit the data, never this file. The study that reads it is');
  L.push('[`../DESIGN-SYSTEM.md`](../DESIGN-SYSTEM.md).*', '');
  L.push('**What this is.** ' + f.total + ' distinct corrections of something a person sees, touches or hears, made by the Principal in ' + f.projects +
    ' projects between April and November 2026, each with its source and its root cause. ' + f.verbatim + ' quote the Principal\'s own words, typing kept; the others are' +
    ' marked [paraphrase] because the source records only a session\'s wording. ' + f.relays + ' further records were the same remark relayed in another file and are' +
    ' listed under the record they repeat (`also`). ' + f.repeat + ' of the ' + f.total + ' name an earlier correction of the same defect.', '');
  L.push('**How it was read.** Four read-only sweeps on 2026-11-09, merged by hand, then classified by root cause (the default that produced the defect), not by symptom:', '');
  for (const [k, v] of Object.entries(c.sweeps)) L.push('- **' + k + '**: ' + v);
  L.push('', 'Client projects are named by what they are, not by their names, because this repository is public.', '');
  L.push('## Counts by root cause', '', '| group | root cause | corrections | projects | name an earlier one | first seen | last seen |', '|---|---|---|---|---|---|---|');
  for (const g of c.groups) for (const k of g.causes) {
    const x = f.causes[k];
    L.push('| ' + g.key + ' | **' + k + '** ' + c.causes[k] + ' | ' + x.n + ' | ' + x.projects + ' | ' + x.repeat + ' | ' + (x.first || '') + ' | ' + (x.last || '') + ' |');
  }
  L.push('', '| group | corrections |', '|---|---|');
  for (const g of c.groups) L.push('| ' + g.title + ' | ' + f.groups[g.key] + ' |');
  L.push('', '## Counts by project and by month', '', '| project | corrections |', '|---|---|');
  for (const [p, n] of Object.entries(f.byProject).sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))) L.push('| ' + p + ' | ' + n + ' |');
  L.push('', '| month | corrections |', '|---|---|');
  for (const [m, n] of Object.entries(f.months).sort()) L.push('| ' + m + ' | ' + n + ' |');
  L.push('', f.lastDay + ' of the corrections were made on 2026-11-09 alone.', '');
  for (const g of c.groups) {
    L.push('## ' + g.title, '');
    for (const k of g.causes) {
      L.push('### ' + k + ' · ' + c.causes[k] + ' (' + f.causes[k].n + ')', '', '| # | date | project | the Principal\'s words | what was wrong | what was asked | source | also |', '|---|---|---|---|---|---|---|---|');
      for (const r of R.filter(r => r.cause === k))
        L.push('| ' + [r.n, r.date, r.project, r.words, r.wrong, r.required, r.source, [r.sweep].concat(r.also).join(' ')].map(cell).join(' | ') + ' |');
      L.push('');
    }
  }
  L.push('## Requests and general statements', '', 'Requests add something rather than correct a defect; they are kept because later corrections refer to them. The general statements name the whole class.', '');
  L.push('| sweep record | date | project | words | source |', '|---|---|---|---|---|');
  for (const r of c.requests.concat(c.statements)) L.push('| ' + [r.sweep, r.date, r.project, r.words, r.source].map(cell).join(' | ') + ' |');
  if (c.candidates && c.candidates.length) {
    L.push('', '## Candidates, not counted', '', c.candidates.length + ' records from the repositories look like answered remarks, but their source does not name or quote the Principal, so they are kept here and left out of every count.', '');
    L.push('| sweep record | date | project | words | root cause, if counted | source |', '|---|---|---|---|---|---|');
    for (const r of c.candidates) L.push('| ' + [r.sweep, r.date, r.project, r.words, r.cause, r.source].map(cell).join(' | ') + ' |');
  }
  return L.join('\n') + '\n';
}

const f = figures(), md = render(f), dst = path.join(here, 'CORPUS.md');
if (process.argv.includes('--check')) {
  const now = fs.existsSync(dst) ? fs.readFileSync(dst, 'utf8') : '';
  if (now !== md) { console.error('corpus: CORPUS.md differs from what corpus.json renders; run node doc/design/corpus/render.js'); process.exit(1); }
  console.log('corpus: CORPUS.md is current (' + f.total + ' corrections)');
} else {
  fs.writeFileSync(dst, md);
  console.log(JSON.stringify(f, null, 1));
}
