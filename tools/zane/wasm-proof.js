#!/usr/bin/env node
'use strict';
/* ==========================================================================
   wasm-proof.js -- the data of the wasm's proof page (doc/design/BINARY.md section 5, item 4; stage S3).

     node tools/zane/wasm-proof.js --bin PATH            write tools/zane/wasm-proof.json
     node tools/zane/wasm-proof.js --bin PATH --check    fail when the file on disk is not what the binary prints now

   The native binary runs `check NAME --json --level N` (with the fixture's symbols when it has any) on every fixture of
   conformance/manifest.json at every level, 1 to 4, and its output is recorded with the source it was run on and the
   sha256 of site/zane.wasm. tools/zane/wasm-proof.html then runs the same sources through the wasm in a browser and
   compares, byte for byte. The names are written with forward slashes, so the record is the same on every platform.

   Exit 0 when written or current, 1 when --check finds it stale, 2 when it cannot run.
   ========================================================================== */
const fs = require('fs'), path = require('path'), os = require('os'), crypto = require('crypto');
const { spawnSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..', '..');
const OUT = path.join(__dirname, 'wasm-proof.json');
const WASM = path.join(ROOT, 'site', 'zane.wasm');
const args = process.argv.slice(2);
const i = args.indexOf('--bin');
const BIN = i >= 0 ? path.resolve(args[i + 1]) : null;
if (!BIN || !fs.existsSync(BIN)) { console.error('wasm-proof: --bin PATH names the native zane binary'); process.exit(2); }
if (!fs.existsSync(WASM)) { console.error('wasm-proof: no site/zane.wasm (zig build -j2 wasm -Doptimize=ReleaseSmall, then copy it)'); process.exit(2); }

const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, 'conformance', 'manifest.json'), 'utf8'));
const TMP = fs.mkdtempSync(path.join(os.tmpdir(), 'zane-wasm-proof-'));
const native = argv => {
  const r = spawnSync(BIN, argv, { cwd: ROOT, encoding: 'utf8' });
  if (r.error) throw r.error;
  return r.stdout;
};

const fixtures = manifest.fixtures.map(fx => {
  const name = 'conformance/fixtures/' + fx.file;
  const sym = [];
  if (fx.symbols) {
    const s = path.join(TMP, fx.file + '.symbols.json');
    fs.writeFileSync(s, JSON.stringify(fx.symbols));
    sym.push('--symbols', s);
  }
  const expect = {};
  for (const level of [1, 2, 3, 4]) expect[level] = native(['check', name, '--json', '--level', String(level), ...sym]);
  return { name, symbols: fx.symbols || null, source: fs.readFileSync(path.join(ROOT, name), 'utf8'), expect };
});
fs.rmSync(TMP, { recursive: true, force: true });

const record = {
  about: 'Generated by tools/zane/wasm-proof.js from the native binary; do not edit. tools/zane/wasm-proof.html runs the same sources through site/zane.wasm and compares.',
  native: native(['version']).trim(),
  wasm: { file: 'site/zane.wasm', bytes: fs.statSync(WASM).size, sha256: crypto.createHash('sha256').update(fs.readFileSync(WASM)).digest('hex') },
  fixtures
};
const text = JSON.stringify(record, null, 1) + '\n';
const runs = fixtures.length * 4;

if (args.includes('--check')) {
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : null;
  if (have !== text) { console.log(`wasm-proof: tools/zane/wasm-proof.json is stale against the binary or site/zane.wasm (run without --check)`); process.exit(1); }
  console.log(`wasm-proof: current -- ${fixtures.length} fixtures x 4 levels = ${runs} envelopes, for zane.wasm ${record.wasm.sha256.slice(0, 12)}`);
} else {
  fs.writeFileSync(OUT, text);
  console.log(`wasm-proof: wrote tools/zane/wasm-proof.json -- ${fixtures.length} fixtures x 4 levels = ${runs} envelopes, for zane.wasm ${record.wasm.sha256.slice(0, 12)} (${record.wasm.bytes} bytes)`);
}
